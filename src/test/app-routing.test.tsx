import { QueryClient } from "@tanstack/react-query";
import { createRouter, rootRouteId } from "@tanstack/react-router";
import { describe, expect, it } from "vitest";

import { routeTree } from "@/routeTree.gen";
import { normalizePagesBase, staticPagePaths } from "../../scripts/pages-config";

// Match routes without running loaders or rendering: loaders may need a server or
// network the test run lacks, and jsdom never loads the stylesheets React waits on.
describe("App routing", () => {
  it("matches a page for / instead of falling back to not found", () => {
    const router = createRouter({ routeTree, context: { queryClient: new QueryClient() } });

    const matches = router.matchRoutes("/");

    expect(matches.at(-1)?.routeId).not.toBe(rootRouteId);
  });

  it.each(staticPagePaths)("matches the static publishing page %s", (path) => {
    const router = createRouter({ routeTree, context: { queryClient: new QueryClient() } });
    expect(router.matchRoutes(path).at(-1)?.routeId).not.toBe(rootRouteId);
  });

  it("normalizes repository and root GitHub Pages prefixes", () => {
    expect(normalizePagesBase("/researchbodh")).toBe("/researchbodh/");
    expect(normalizePagesBase("/")).toBe("/");
    expect(normalizePagesBase("")).toBe("/");
  });
});
